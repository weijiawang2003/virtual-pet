// mulberry32 — small, fast, deterministic PRNG. Returns a generator function.
// Given the same seed, the same sequence of values is produced, which makes
// `selectPhrase` testable without globally-shared RNG state.
export function mulberry32(seed: number): () => number {
  let a = seed | 0;
  return function next(): number {
    a = (a + 0x6d2b79f5) | 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
